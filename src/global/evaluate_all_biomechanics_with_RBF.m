function evaluation_result_total = evaluate_all_biomechanics_with_RBF( ...
    target_biomechanics_total, visualize_option)

biomechanics_list = fields(target_biomechanics_total);
plot_options = struct;

plot_option_RBF_ankle_moment = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-1 2], 'view', [20, 30], ...
    'clim', [0 1]);

plot_option_RBF_ankle_angle_stance = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-40 40], 'view', [10, 35], ...
    'clim', [-50 50]);

plot_option_RBF_ankle_angle_swing = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-40 40], 'view', [10, 35], ...
    'clim', [-50 50]);

plot_option_RBF_knee_moment = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-1 2], 'view', [20, 30], ...
    'clim', [0 1]);

plot_option_RBF_knee_angle_stance = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-10 100], 'view', [10, 15], ...
    'clim', [-10 100]);

plot_option_RBF_knee_angle_swing = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-10 100], 'view', [20, 50], ...
    'clim', [-10 100]);

plot_option_RBF_hip_moment = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-1 2], 'view', [20, 30], ...
    'clim', [0 1]);

plot_option_RBF_hip_angle_stance = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-75 75], 'view', [20, 30], ...
    'clim', [-75 75]);

plot_option_RBF_hip_angle_swing = struct('visualize', visualize_option, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-75 75], 'view', [20, 30], ...
    'clim', [-75 75]);

plot_option_false = struct('visualize', false, ...
    'xlim', [-40 40], 'ylim', [0 100], ...
    'zlim', [-1 2], 'view', [20, 30], ...
    'clim', [0 1]);

plot_options.avg_ankle_moment_stance_total = plot_option_RBF_ankle_moment;
plot_options.avg_ankle_angle_stance_total = plot_option_RBF_ankle_angle_stance;
plot_options.avg_ankle_angle_swing_total = plot_option_RBF_ankle_angle_swing;
plot_options.avg_knee_moment_stance_total = plot_option_RBF_knee_moment;
plot_options.avg_knee_angle_stance_total = plot_option_RBF_knee_angle_stance;
plot_options.avg_knee_angle_swing_total = plot_option_RBF_knee_angle_swing;
plot_options.avg_hip_moment_stance_total = plot_option_RBF_hip_moment;
plot_options.avg_hip_angle_stance_total = plot_option_RBF_hip_angle_stance;
plot_options.avg_hip_angle_swing_total = plot_option_RBF_hip_angle_swing;

evaluation_result_total = struct;

for i = 1:length(biomechanics_list)
    moment_positive_zero = false;

    target_biomechanics_name = biomechanics_list{i};

    if contains(target_biomechanics_name, 'mean') || contains(target_biomechanics_name, 'std')
        %% Skip mean/std informations. Not for plotting or RBF blending.
        continue
    end

    target_biomechanics = target_biomechanics_total.(target_biomechanics_name);
    plot_option_full = plot_options.(target_biomechanics_name);

    [target_joint, target_state, target_biomech] = ...
        local_parse_biomechanics_name(target_biomechanics_name);

    plot_option_full = configure_biomechanics_surface_plot( ...
        plot_option_full, target_joint, target_state, target_biomech, ...
        "Global RBF model");
    
    %% For later use, leave this part (test with different r values)
    if contains(target_biomechanics_name, 'ankle')
        r_coeff = 1e-8;
    else
        r_coeff = 1e-8;
    end

    evaluation_result = evaluate_selected_biomechanics_with_RBF( ...
    target_biomechanics, r_coeff, ...
    plot_option_full, ...
    plot_option_false, ...
    plot_option_false, ...
    moment_positive_zero ...
    );

    evaluation_result_total.(target_biomechanics_name) = evaluation_result;
end

end

function [targetJoint, targetState, targetBiomech] = ...
    local_parse_biomechanics_name(targetName)

%% Parse names such as avg_hip_angle_stance_total.

    tokens = split(string(targetName), "_");

    if numel(tokens) < 5 || tokens(1) ~= "avg" || tokens(end) ~= "total"
        error('Unexpected biomechanics field name: %s', targetName);
    end

    targetJoint = tokens(2);
    targetBiomech = tokens(3);
    targetState = tokens(4);
end
