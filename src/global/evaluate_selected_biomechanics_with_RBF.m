function evaluation_result = evaluate_selected_biomechanics_with_RBF( ...
    target_biomechanics, r_coeff, ...
    plot_option_full, ...
    plot_option_ascent, ...
    plot_option_descent, ...
    moment_positive_zero ...
    )

normalized_phase = linspace(0,100,101);

%% Define slope ranges - 4 different presets for each ramp/stairs + LW
slope_full = [-35, -30, -24, -20, ...
    -11, -9, -7, ...
    -5, 0, 5, ...
    7, 9, 11, ...
    20, 24, 30, 35];

slope_descent_full = [-35, -30, -24, -20, ...
    -11, -9, -7, -5, 0];

slope_ascent_full = [0, ...
    5, 7, 9, 11, ...
    20, 24, 30, 35];

slope_ascent_full_with_RD = [-11, -9, -7, -5, 0, ...
    5, 7, 9, 11, ...
    20, 24, 30, 35];

slope_descent_full_with_RA = [-35, -30, -24, -20, ...
    -11, -9, -7, -5, 0, ...
    5, 7, 9, 11];

slope_ascent_ramp = [0, 5, 7, 9, 11];

slope_ascent_stair = [0, 20, 24, 30, 35];

slope_descent_ramp = [-11, -9, -7, -5, 0];

slope_descent_stair = [-35, -30, -24, -20, 0];

%% Verify the leave_slopes_out function works
% 1. Full slope
[target_biomechanics_surf_full, sorted_slope_continuous_full] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_full);

% 2a. Full ascending
[target_biomechanics_surf_ascent_full, sorted_slope_continuous_ascent] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_ascent_full);

% 2b. Full ascending + RD
[target_biomechanics_surf_ascent_full_with_RD, sorted_slope_continuous_ascent_with_RD] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_ascent_full_with_RD);

% 2c. RA only
[target_biomechanics_surf_ascent_ramp, sorted_slope_continuous_ascent_ramp] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_ascent_ramp);

% 2d. SA only
[target_biomechanics_surf_ascent_stair, sorted_slope_continuous_ascent_stair] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_ascent_stair);

% 3a. Full descending
[target_biomechanics_surf_descent_full, sorted_slope_continuous_descent] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_descent_full);

% 3b. Full descending + RA
[target_biomechanics_surf_descent_full_with_RA, sorted_slope_continuous_descent_with_RA] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_descent_full_with_RA);

% 3c. RD only
[target_biomechanics_surf_descent_ramp, sorted_slope_continuous_descent_ramp] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_descent_ramp);

% 3d. SD only
[target_biomechanics_surf_descent_stair, sorted_slope_continuous_descent_stair] = leave_slopes_out( ...
    target_biomechanics, slope_full, slope_descent_stair);

%% Verify the piecewise_2dpoly functions
% Full
[fitModel_full, fitted_biomechanics_full] = piecewise_2dpoly( ...
    target_biomechanics_surf_full, slope_full, sorted_slope_continuous_full, ...
    "poly44", 0);

% Ascent
[fitModel_ascent_full, fitted_biomechanics_ascent_full] = piecewise_2dpoly( ...
    target_biomechanics_surf_ascent_full, slope_ascent_full, sorted_slope_continuous_full, ...
    "poly44", 0);

[fitModel_ascent_full_with_RD, fitted_biomechanics_ascent_full_with_RD] = piecewise_2dpoly( ...
    target_biomechanics_surf_ascent_full_with_RD, slope_ascent_full_with_RD, sorted_slope_continuous_full, ...
    "poly44", 0);

[fitModel_ascent_ramp, fitted_biomechanics_ascent_ramp] = piecewise_2dpoly( ...
    target_biomechanics_surf_ascent_ramp, slope_ascent_ramp, sorted_slope_continuous_full, ...
    "poly44", 0);

[fitModel_ascent_stair, fitted_biomechanics_ascent_stair] = piecewise_2dpoly( ...
    target_biomechanics_surf_ascent_stair, slope_ascent_stair, sorted_slope_continuous_full, ...
    "poly44", 0);

% Descent
[fitModel_descent_full, fitted_biomechanics_descent_full] = piecewise_2dpoly( ...
    target_biomechanics_surf_descent_full, slope_descent_full, sorted_slope_continuous_full, ...
    "poly44", 0);

[fitModel_descent_full_with_RA, fitted_biomechanics_descent_full_with_RA] = piecewise_2dpoly( ...
    target_biomechanics_surf_descent_full_with_RA, slope_descent_full_with_RA, sorted_slope_continuous_full, ...
    "poly44", 0);

[fitModel_descent_ramp, fitted_biomechanics_descent_ramp] = piecewise_2dpoly( ...
    target_biomechanics_surf_descent_ramp, slope_descent_ramp, sorted_slope_continuous_full, ...
    "poly44", 0);

[fitModel_descent_stair, fitted_biomechanics_descent_stair] = piecewise_2dpoly( ...
    target_biomechanics_surf_descent_stair, slope_descent_stair, sorted_slope_continuous_full, ...
    "poly44", 0);

% RBF-blending
% r_coeff = 1e-8;

z_RBF_interp = merge_RBF( ...
    fitted_biomechanics_ascent_full(:, 36:end), fitted_biomechanics_descent_full(:, 1:36), ...
    r_coeff, moment_positive_zero ...
    );

%% Evaluate each piecewise fits
% Full RBF evaluation
[RBF_full, similarity_00] = evaluate_model( ...
    target_biomechanics_surf_full, slope_full, ...
    z_RBF_interp, sorted_slope_continuous_full, plot_option_full);

% Ascent
[RBF_in_ascent, similarity_10] = evaluate_model( ...
    target_biomechanics_surf_ascent_full, slope_ascent_full, ...
    z_RBF_interp, sorted_slope_continuous_full, plot_option_ascent);

[model_fullslope_in_ascent, similarity_11] = evaluate_model( ...
    target_biomechanics_surf_ascent_full, slope_ascent_full, ...
    fitted_biomechanics_full, sorted_slope_continuous_full, plot_option_ascent);

[model_using_ascent_full_with_RD, similarity_12] = evaluate_model( ...
    target_biomechanics_surf_ascent_full, slope_ascent_full, ...
    fitted_biomechanics_ascent_full_with_RD, sorted_slope_continuous_full, plot_option_ascent);

[model_using_ascent_full, similarity_13] = evaluate_model( ...
    target_biomechanics_surf_ascent_full, slope_ascent_full, ...
    fitted_biomechanics_ascent_full, sorted_slope_continuous_full, plot_option_ascent);

[model_using_ascent_ramp, similarity_15] = evaluate_model( ...
    target_biomechanics_surf_ascent_full, slope_ascent_full, ...
    fitted_biomechanics_ascent_ramp, sorted_slope_continuous_full, plot_option_ascent);

[model_using_ascent_stair, similarity_14] = evaluate_model( ...
    target_biomechanics_surf_ascent_full, slope_ascent_full, ...
    fitted_biomechanics_ascent_stair, sorted_slope_continuous_full, plot_option_ascent);

% Descent
[RBF_in_descent, similarity_20] = evaluate_model( ...
    target_biomechanics_surf_descent_full, slope_descent_full, ...
    z_RBF_interp, sorted_slope_continuous_full, plot_option_descent);

[model_fullslope_in_descent, similarity_21] = evaluate_model( ...
    target_biomechanics_surf_descent_full, slope_descent_full, ...
    fitted_biomechanics_full, sorted_slope_continuous_full, plot_option_descent);

[model_using_descent_full_with_RA, similarity_22] = evaluate_model( ...
    target_biomechanics_surf_descent_full, slope_descent_full, ...
    fitted_biomechanics_descent_full_with_RA, sorted_slope_continuous_full, plot_option_descent);

[model_using_descent_full, similarity_23] = evaluate_model( ...
    target_biomechanics_surf_descent_full, slope_descent_full, ...
    fitted_biomechanics_descent_full, sorted_slope_continuous_full, plot_option_descent);

[model_using_descent_ramp, similarity_25] = evaluate_model( ...
    target_biomechanics_surf_descent_full, slope_descent_full, ...
    fitted_biomechanics_descent_ramp, sorted_slope_continuous_full, plot_option_descent);

[model_using_descent_stair, similarity_24] = evaluate_model( ...
    target_biomechanics_surf_descent_full, slope_descent_full, ...
    fitted_biomechanics_descent_stair, sorted_slope_continuous_full, plot_option_descent);

similarities_ascent = {
    similarity_10;    
    similarity_11;
    similarity_12;
    similarity_13;
    similarity_14;
    similarity_15
};

similarities_descent = {
    similarity_20;
    similarity_21;
    similarity_22;
    similarity_23;
    similarity_24;
    similarity_25
};

evaluation_result.RBF_in_ascent = RBF_in_ascent;
evaluation_result.model_fullslope_in_ascent = model_fullslope_in_ascent;
evaluation_result.model_using_ascent_full_with_RD = model_using_ascent_full_with_RD;
evaluation_result.model_using_ascent_full = model_using_ascent_full;
evaluation_result.model_using_ascent_ramp = model_using_ascent_ramp;
evaluation_result.model_using_ascent_stair = model_using_ascent_stair;
evaluation_result.similarities_ascent = similarities_ascent;

evaluation_result.RBF_in_descent = RBF_in_descent;
evaluation_result.model_fullslope_in_descent = model_fullslope_in_descent;
evaluation_result.model_using_descent_full_with_RA = model_using_descent_full_with_RA;
evaluation_result.model_using_descent_full = model_using_descent_full;
evaluation_result.model_using_descent_ramp = model_using_descent_ramp;
evaluation_result.model_using_descent_stair = model_using_descent_stair;
evaluation_result.similarities_descent = similarities_descent;

evaluation_result.RBF_in_full_domain = z_RBF_interp;

end