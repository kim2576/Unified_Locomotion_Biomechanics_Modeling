function RBF_model_full = build_rbf_model_struct(evaluation_result_total)

%{
Create the compact unified-RBF model structure.

  RBF_model_full = BUILD_RBF_MODEL_STRUCT(evaluation_result_total)

Converts the verbose field names returned by
evaluate_all_biomechanics_with_RBF into the compact joint/variable names
used by downstream controller-parameter derivation scripts.
%}

    required_fields = { ...
        'avg_ankle_angle_stance_total', ...
        'avg_ankle_moment_stance_total', ...
        'avg_ankle_angle_swing_total', ...
        'avg_knee_angle_stance_total', ...
        'avg_knee_moment_stance_total', ...
        'avg_knee_angle_swing_total', ...
        'avg_hip_angle_stance_total', ...
        'avg_hip_moment_stance_total', ...
        'avg_hip_angle_swing_total'};

    missing_fields = required_fields(~isfield(evaluation_result_total, required_fields));
    if ~isempty(missing_fields)
        error('build_rbf_model_struct:MissingField', ...
            'Missing required evaluation field(s): %s', ...
            strjoin(missing_fields, ', '));
    end

    RBF_model_full = struct;

    RBF_model_full.ankle_angle_stance = ...
        evaluation_result_total.avg_ankle_angle_stance_total;
    RBF_model_full.ankle_moment_stance = ...
        evaluation_result_total.avg_ankle_moment_stance_total;
    RBF_model_full.ankle_angle_swing = ...
        evaluation_result_total.avg_ankle_angle_swing_total;

    RBF_model_full.knee_angle_stance = ...
        evaluation_result_total.avg_knee_angle_stance_total;
    RBF_model_full.knee_moment_stance = ...
        evaluation_result_total.avg_knee_moment_stance_total;
    RBF_model_full.knee_angle_swing = ...
        evaluation_result_total.avg_knee_angle_swing_total;

    RBF_model_full.hip_angle_stance = ...
        evaluation_result_total.avg_hip_angle_stance_total;
    RBF_model_full.hip_moment_stance = ...
        evaluation_result_total.avg_hip_moment_stance_total;
    RBF_model_full.hip_angle_swing = ...
        evaluation_result_total.avg_hip_angle_swing_total;
end
