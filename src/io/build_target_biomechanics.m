function target_biomechanics_total = build_target_biomechanics( ...
    camargo_data_struct, molinaro_data_struct)

%{
Convert preprocessed structures to phase x slope.

Output matrices used by the fitting code have:
rows    = normalized phase (101 samples)
columns = terrain slopes (17 conditions, ascending -35 to +35 deg)
%}

    target_biomechanics_total = struct;

    %% Ankle: Molinaro data have offset by load_preprocessed_biomechanics().
    target_biomechanics_total.avg_ankle_moment_stance_total = ...
        molinaro_data_struct.ankle_moment_stance';
    target_biomechanics_total.avg_ankle_angle_stance_total = ...
        molinaro_data_struct.ankle_angle_stance';
    target_biomechanics_total.avg_ankle_angle_swing_total = ...
        molinaro_data_struct.ankle_angle_swing';

    target_biomechanics_total.avg_ankle_moment_stance_peaks_mean = ...
        molinaro_data_struct.ankle_moment_stance_peaks_mean;
    target_biomechanics_total.avg_ankle_moment_stance_peaks_std = ...
        molinaro_data_struct.ankle_moment_stance_peaks_std;
    target_biomechanics_total.avg_ankle_angle_stance_HCs_mean = ...
        molinaro_data_struct.ankle_angle_stance_HCs_mean;
    target_biomechanics_total.avg_ankle_angle_stance_HCs_std = ...
        molinaro_data_struct.ankle_angle_stance_HCs_std;
    target_biomechanics_total.avg_ankle_angle_swing_peaks_mean = ...
        molinaro_data_struct.ankle_angle_swing_peaks_mean;
    target_biomechanics_total.avg_ankle_angle_swing_peaks_std = ...
        molinaro_data_struct.ankle_angle_swing_peaks_std;

    %% Knee
    target_biomechanics_total.avg_knee_moment_stance_total = ...
        camargo_data_struct.knee_moment_stance';
    target_biomechanics_total.avg_knee_angle_stance_total = ...
        camargo_data_struct.knee_angle_stance';
    target_biomechanics_total.avg_knee_angle_swing_total = ...
        camargo_data_struct.knee_angle_swing';

    target_biomechanics_total.avg_knee_moment_stance_peaks_mean = ...
        camargo_data_struct.knee_moment_stance_peaks_mean;
    target_biomechanics_total.avg_knee_moment_stance_peaks_std = ...
        camargo_data_struct.knee_moment_stance_peaks_std;
    target_biomechanics_total.avg_knee_angle_stance_HCs_mean = ...
        camargo_data_struct.knee_angle_stance_HCs_mean;
    target_biomechanics_total.avg_knee_angle_stance_HCs_std = ...
        camargo_data_struct.knee_angle_stance_HCs_std;
    target_biomechanics_total.avg_knee_angle_swing_peaks_mean = ...
        camargo_data_struct.knee_angle_swing_peaks_mean;
    target_biomechanics_total.avg_knee_angle_swing_peaks_std = ...
        camargo_data_struct.knee_angle_swing_peaks_std;

    %% Hip
    target_biomechanics_total.avg_hip_moment_stance_total = ...
        camargo_data_struct.hip_moment_stance';
    target_biomechanics_total.avg_hip_angle_stance_total = ...
        camargo_data_struct.hip_angle_stance';
    target_biomechanics_total.avg_hip_angle_swing_total = ...
        camargo_data_struct.hip_angle_swing';

    target_biomechanics_total.avg_hip_moment_stance_peaks_mean = ...
        camargo_data_struct.hip_moment_stance_peaks_mean;
    target_biomechanics_total.avg_hip_moment_stance_peaks_std = ...
        camargo_data_struct.hip_moment_stance_peaks_std;
    target_biomechanics_total.avg_hip_angle_stance_HCs_mean = ...
        camargo_data_struct.hip_angle_stance_HCs_mean;
    target_biomechanics_total.avg_hip_angle_stance_HCs_std = ...
        camargo_data_struct.hip_angle_stance_HCs_std;
    target_biomechanics_total.avg_hip_angle_swing_peaks_mean = ...
        camargo_data_struct.hip_angle_swing_peaks_mean;
    target_biomechanics_total.avg_hip_angle_swing_peaks_std = ...
        camargo_data_struct.hip_angle_swing_peaks_std;
end
